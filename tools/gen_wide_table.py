#!/usr/bin/env python3
"""Generates src/wide_table.inc: the code points a terminal draws two columns
wide, which are East_Asian_Width W (Wide) and F (Fullwidth).

Usage:
    curl -O https://www.unicode.org/Public/17.0.0/ucd/EastAsianWidth.txt
    python3 tools/gen_wide_table.py EastAsianWidth.txt > src/wide_table.inc

Run it again with the new file when a Unicode release adds wide characters.
The Unicode version is read from the file's header and written into the
output.
"""
import re
import sys


def main(path):
    version = None
    ranges = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if version is None:
                m = re.match(r"# EastAsianWidth-(\d+\.\d+\.\d+)\.txt", line)
                if m:
                    version = m.group(1)
            data = line.split("#", 1)[0].strip()
            if not data:
                continue
            cps, prop = (part.strip() for part in data.split(";"))
            if prop not in ("W", "F"):
                continue
            lo_text, _, hi_text = cps.partition("..")
            lo = int(lo_text, 16)
            hi = int(hi_text or lo_text, 16)
            if ranges and ranges[-1][1] + 1 == lo:
                ranges[-1][1] = hi  # merge adjacent ranges
            else:
                ranges.append([lo, hi])
    if version is None:
        sys.exit("no EastAsianWidth-X.Y.Z.txt header found in " + path)

    out = []
    out.append("// Generated by tools/gen_wide_table.py from Unicode %s EastAsianWidth.txt." % version)
    out.append("// Do not edit. Code points with East_Asian_Width W or F, as sorted")
    out.append("// inclusive ranges: terminals draw these two columns wide.")
    out.append("constexpr char32_t kWideRanges[][2] = {")
    for lo, hi in ranges:
        out.append("    {0x%X, 0x%X}," % (lo, hi))
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
